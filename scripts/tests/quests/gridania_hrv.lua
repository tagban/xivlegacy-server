-- Botanists' Guild: Hrv200 "Gridanian Roots", Hrv300 "The Grass is Always
-- Greener", Hrv306 "A Moogle Bouquet".
--
-- Quest-hook legs only (the `walkthrough` bridge); each case seeds the
-- sequence it walks.

-- Actor class ids (from scripts/lua/quests/hrv/*.lua).
local ONGUEN      = 1000074
local OPYLTYL     = 1000236
local CICELY      = 1000326
local NOGELOIX    = 1000597
local EBURHART    = 1000629
local LINETTE     = 1000861
local VNABYANO    = 1001101
local SANDRE      = 1001102
local PENELOPE    = 1700001
local QUARRYMILL  = 1091120
local RYCHYLD     = 1091121
local FLOWER_BEDS = 1091122
local MOOGLE_BEDS = 1091123

local INK         = 11000085
local PINE_BRANCH = 11000086
local FOUL_NUT    = 11000087
local YARZON_DUNG = 11000043
local PEARL_CLOVER = 11000123

describe("Gridanian Roots (Hrv200)", function()
    it("offer: Opyltyl asks you to pay your respects to the wood", function()
        local w = walkthrough.start("Hrv200", 65535)
        w:stateChange(65535):expectEnpc(OPYLTYL, QFLAG_TALK)
        w:talk(OPYLTYL):expectDelegate("processEventOpyltylStart"):answer(1)
    end)

    it("SEQ_000: the botanists' word, then Cicely", function()
        local w = walkthrough.start("Hrv200", 0)
        w:stateChange(0):expectEnpc(CICELY, QFLAG_TALK):expectEnpc(OPYLTYL, QFLAG_NONE)
        w:expectMarkers(11048001)
        w:talk(OPYLTYL):expectDelegate("processEvent005_2"):ack()
        w:talk(ONGUEN):expectDelegate("processEvent005_3"):ack()
        w:talk(EBURHART):expectDelegate("processEvent005_4"):ack()
        w:talk(VNABYANO):expectDelegate("processEvent005_5"):ack()
        w:talk(CICELY):expectDelegate("processEvent010"):ack():expectStartSequence(10)
    end)

    it("SEQ_010: the weeds by Quarrymill", function()
        local w = walkthrough.start("Hrv200", 10)
        w:stateChange(10):expectEnpc(QUARRYMILL, QFLAG_PUSH)
        w:expectMarkers(11048002)
        w:talk(CICELY):expectDelegate("processEvent010_2"):ack()
        w:talk(OPYLTYL):expectDelegate("processEvent010_3"):ack()
        w:push(QUARRYMILL):expectDelegate("processEvent020"):ack():expectStartSequence(20)
    end)

    it("SEQ_020: Opyltyl's payment", function()
        local w = walkthrough.start("Hrv200", 20)
        w:stateChange(20):expectEnpc(OPYLTYL, QFLAG_REWARD)
        w:expectMarkers(11048003)
        w:talk(ONGUEN):expectDelegate("processEvent020_2"):ack()
        w:talk(VNABYANO):expectDelegate("processEvent020_3"):ack()
        w:talk(EBURHART):expectDelegate("processEvent020_4"):ack()
        w:talk(OPYLTYL):expectDelegate("processEvent030"):ack()
            :expectDelegate("sqrwa"):ack()
            :expectGil(20000):expectExp(2000)
            :expectCompleted(110480)
    end)
end)

describe("The Grass is Always Greener (Hrv300)", function()
    it("offer: Opyltyl asks you to Ul'dah", function()
        local w = walkthrough.start("Hrv300", 65535)
        w:stateChange(65535):expectEnpc(OPYLTYL, QFLAG_TALK)
        w:talk(OPYLTYL):expectDelegate("processEventOpyltylStart"):answer(1)
    end)

    it("SEQ_000: Cicely wants a story", function()
        local w = walkthrough.start("Hrv300", 0)
        w:stateChange(0):expectEnpc(CICELY, QFLAG_TALK)
        w:expectMarkers(11048101)
        w:talk(OPYLTYL):expectDelegate("processEvent005_2"):ack()
        w:talk(ONGUEN):expectDelegate("processEvent005_3"):ack()
        w:talk(CICELY):expectDelegate("processEvent010"):ack():expectStartSequence(10)
    end)

    it("SEQ_010: Penelope at the Carline Canopy", function()
        local w = walkthrough.start("Hrv300", 10)
        w:stateChange(10):expectEnpc(PENELOPE, QFLAG_TALK)
        w:expectMarkers()
        w:talk(CICELY):expectDelegate("processEvent010_2"):ack()
        w:talk(OPYLTYL):expectDelegate("processEvent010_3"):ack()
        w:talk(PENELOPE):expectDelegate("processEvent013"):ack():expectStartSequence(13)
    end)

    it("SEQ_013: Cicely names her price", function()
        local w = walkthrough.start("Hrv300", 13)
        w:stateChange(13):expectEnpc(CICELY, QFLAG_TALK)
        w:talk(PENELOPE):expectDelegate("processEvent013_2"):ack()
        w:talk(CICELY):expectDelegate("processEvent014"):ack():expectStartSequence(14)
    end)

    it("SEQ_014: without the branch and the nut, Cicely waits", function()
        local w = walkthrough.start("Hrv300", 14)
        w:give(PINE_BRANCH, 1)
        w:talk(CICELY):expectDelegate("processEvent014_2"):ack():expectNoRemoveItem()
        w:expectSequence(14)
    end)

    it("SEQ_014: the branch and the nut for the ink", function()
        local w = walkthrough.start("Hrv300", 14)
        w:stateChange(14):expectEnpc(CICELY, QFLAG_TALK)
        w:give(PINE_BRANCH, 1)
        w:give(FOUL_NUT, 1)
        w:talk(CICELY):expectDelegate("processEvent015"):ack()
            :expectRemoveItem(PINE_BRANCH, 1)
            :expectRemoveItem(FOUL_NUT, 1)
            :expectAddItem(INK, 1)
            :expectStartSequence(15)
    end)

    it("SEQ_015: the ink, and Penelope's tale", function()
        local w = walkthrough.start("Hrv300", 15)
        w:stateChange(15):expectEnpc(PENELOPE, QFLAG_TALK)
        w:talk(CICELY):expectDelegate("processEvent015_2"):ack()
        w:talk(PENELOPE):expectDelegate("processEvent017"):ack():expectStartSequence(17)
    end)

    it("SEQ_017: the ghost ship for the specimen", function()
        local w = walkthrough.start("Hrv300", 17)
        w:stateChange(17):expectEnpc(CICELY, QFLAG_TALK)
        w:expectMarkers(11048102)
        w:talk(PENELOPE):expectDelegate("processEvent018"):ack()
        w:talk(EBURHART):expectDelegate("processEvent017_2"):ack()
        w:give(INK, 1)
        w:talk(CICELY):expectDelegate("processEvent020"):ack()
            :expectRemoveItem(INK, 1)
            :expectStartSequence(20)
    end)

    it("SEQ_020: Nogeloix takes the specimen", function()
        local w = walkthrough.start("Hrv300", 20)
        w:stateChange(20):expectEnpc(NOGELOIX, QFLAG_TALK)
        w:talk(CICELY):expectDelegate("processEvent020_2"):ack()
        w:talk(LINETTE):expectDelegate("processEvent020_6"):ack()
        w:talk(NOGELOIX):expectDelegate("processEvent025"):ack():expectStartSequence(25)
    end)

    it("SEQ_025: Linette and Nenekko", function()
        local w = walkthrough.start("Hrv300", 25)
        w:stateChange(25):expectEnpc(LINETTE, QFLAG_TALK)
        w:expectMarkers(11048103)
        w:talk(NOGELOIX):expectDelegate("processEvent025_2"):ack()
        w:talk(LINETTE):expectDelegate("processEvent030"):ack():expectStartSequence(30)
    end)

    it("SEQ_030: Opyltyl's payment", function()
        local w = walkthrough.start("Hrv300", 30)
        w:stateChange(30):expectEnpc(OPYLTYL, QFLAG_REWARD)
        w:expectMarkers(11048104)
        w:talk(LINETTE):expectDelegate("processEvent030_2"):ack()
        w:talk(VNABYANO):expectDelegate("processEvent030_5"):ack()
        w:talk(OPYLTYL):expectDelegate("processEvent040"):ack()
            :expectDelegate("sqrwa"):ack()
            :expectGil(30000):expectExp(3000)
            :expectCompleted(110481)
    end)
end)

