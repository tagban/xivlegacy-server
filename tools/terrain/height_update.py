#!/usr/bin/env python3
"""Write the follow-up seed that moves already-seeded monsters onto the ground.

Seeds are recorded by file name, so a database that already applied
101_world_monster_spawns.sql never re-runs it after it is regenerated. This compares the 101
that such databases applied (git revision --old, default the commit that first added it) with
the current file and writes UPDATEs for every spawn whose position changed. On a fresh
database the current 101 already has these positions, so the updates change nothing.

Usage: height_update.py [--old REV] [--out common/sql/seed/292_world_monster_spawn_heights.sql]
"""

import argparse
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent.parent
SEED = "common/sql/seed/101_world_monster_spawns.sql"
OUT = REPO / "common" / "sql" / "seed" / "292_world_monster_spawn_heights.sql"
ROW = re.compile(r"spawn_locations .*?VALUES \((\d+), '[^']*', \d+, ([-\d.]+), ([-\d.]+), ([-\d.]+),")


def positions(text):
    return {int(b): (x, y, z) for b, x, y, z in ROW.findall(text)}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--old", default="306be0b", help="git revision of the 101 already applied")
    ap.add_argument("--out", default=str(OUT))
    args = ap.parse_args()
    old = positions(subprocess.run(["git", "-C", str(REPO), "show", f"{args.old}:{SEED}"],
                                   check=True, capture_output=True, text=True).stdout)
    new = positions((REPO / SEED).read_text())
    if set(old) != set(new):
        sys.exit("spawn ids differ between the two seeds; this script only moves existing spawns")
    lines = [
        "-- Generated by tools/terrain/height_update.py - do not edit by hand.",
        "-- Moves the seed-101 monsters of databases that applied it before the ground heights",
        "-- (tools/terrain) onto the ground. A no-op where the current seed 101 was applied.",
        "",
    ]
    n = 0
    for b in sorted(new):
        (ox, oy, oz), (x, y, z) = old[b], new[b]
        if (ox, oy, oz) == (x, y, z):
            continue
        sets = [f"positionY = {y}"]
        if (ox, oz) != (x, z):  # a point moved off a cliff face onto nearby ground
            sets = [f"positionX = {x}", f"positionY = {y}", f"positionZ = {z}"]
        lines.append(f"UPDATE server_battlenpc_spawn_locations SET {', '.join(sets)} WHERE bnpcId = {b};")
        n += 1
    Path(args.out).write_text("\n".join(lines) + "\n")
    print(f"{n} spawns updated -> {args.out}")


if __name__ == "__main__":
    sys.exit(main())
